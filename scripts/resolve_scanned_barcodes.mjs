const CONCURRENCY = 5;
let done = 0;
const ok = [], failed = [];

async function resolveOne(ean) {
  try {
    const r = await fetch(`${BASE}/functions/v1/admin-resolve-barcode`, {
      method: "POST",
      headers: { Authorization: `Bearer ${SERVICE}`, "Content-Type": "application/json" },
      body: JSON.stringify({ ean }),
    });
    const d = await r.json().catch(() => ({}));
    if (d?.ok) {
      ok.push({ ean, name: d.name, score: d.score, label: d.scoreLabel });
      console.log(`OK  ${ean}  [${d.score}/${d.scoreLabel}]  ${d.brand ?? ""} ${(d.name ?? "").slice(0, 40)}`);
    } else {
      failed.push({ ean, reason: d?.reason ?? `http ${r.status}` });
      console.log(`--  ${ean}  (${d?.reason ?? "http " + r.status})`);
    }
  } catch (e) {
    failed.push({ ean, reason: String(e.message).slice(0, 60) });
    console.log(`ERR ${ean}  ${e.message}`);
  } finally {
    done++;
    if (done % 20 === 0) console.log(`... ${done}/${EANS.length} (ok=${ok.length} echec=${failed.length})`);
  }
}

// Pool de concurrence simple.
const queue = [...EANS];
async function worker() {
  while (queue.length) {
    const ean = queue.shift();
    await resolveOne(ean);
  }
}
await Promise.all(Array.from({ length: CONCURRENCY }, worker));

